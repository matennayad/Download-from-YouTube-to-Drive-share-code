#!/bin/sh
# ============================================================
# הפעלת הקונטיינר
# ============================================================
# שני תהליכים: שירות ה-PO Token, ואחריו האפליקציה.
#
# ה-PO Token הוא אסימון שיוטיוב דורש כהוכחה שהבקשה הגיעה
# מדפדפן אמיתי. בלעדיו מתקבל "Sign in to confirm you're not a
# bot", ו-yt-dlp נופל אחורה לעוגיות שפגות מדי כמה שבועות.
# השירות מייצר אותו מקומית בכל בקשה, בלי חשבון ובלי עוגיות.
#
# app.py כבר מפנה את yt-dlp ל-127.0.0.1:4416 - כאן רק דואגים
# שיהיה שם מי שיענה.

set -e

POT_PORT="${POT_PORT:-4416}"

echo "מפעיל את שירות ה-PO Token על פורט $POT_PORT..."

node /opt/bgutil/server/build/main.js --port "$POT_PORT" &
POT_PID=$!

# ממתינים שהשירות יענה. אם הוא לא עולה, האפליקציה עדיין רצה -
# היא פשוט תחזור להתנהגות הקודמת עם עוגיות, וזה עדיף על
# קונטיינר שלא עולה בכלל.
i=0
while [ "$i" -lt 30 ]; do

  if curl -sf "http://127.0.0.1:$POT_PORT/ping" >/dev/null 2>&1; then
    echo "שירות ה-PO Token מוכן."
    break
  fi

  if ! kill -0 "$POT_PID" 2>/dev/null; then
    echo "אזהרה: שירות ה-PO Token נפל. ההורדות ימשיכו בלעדיו."
    break
  fi

  i=$((i + 1))
  sleep 1
done

if [ "$i" -ge 30 ]; then
  echo "אזהרה: שירות ה-PO Token לא ענה תוך 30 שניות. ממשיכים בלעדיו."
fi

echo "מפעיל את האפליקציה..."

exec python3 app.py
